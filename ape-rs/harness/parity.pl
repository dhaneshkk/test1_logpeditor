/*  parity.pl — Scryer-side half of `ape-parity` (replaces tools/score.py and run_scryer.pl).
    Loaded into the embedded Scryer machine next to the converted APE. The SWI reference results
    and the test suite are consulted as modules generated by the Rust driver.
*/
:- module(parity, [suite_check/5, variant/2, om_ref/4, test_text/2, om_run/4]).
:- use_module(library(lists)).
:- use_module(library(terms)).
:- use_module(library(iso_ext)).
:- use_module(library(charsio)).
:- use_module('../prolog-scryer/parser/ace_to_drs').
:- use_module('../prolog-scryer/swi_compat', [call_with_time_limit/2, exclude/3]).
:- op(400, fx, -). :- op(400, fx, ~). :- op(500, xfx, =>). :- op(500, xfx, v).

%% variant/2 (=@= in SWI): structurally equal up to consistent variable renaming.
variant(A, B) :-
    \+ \+ ( copy_term(A, A1), copy_term(B, B1),
            numbervars(A1, 0, N), numbervars(B1, 0, N), A1 == B1 ).

%% suite_check(+N, -GoldNE, -SwiNE, -ScrNE, -Same)
%%   *NE ∈ {0,1}: DRS non-empty (text accepted as ACE); Same = 1 iff Scryer DRS =@= SWI DRS.
suite_check(N, G, R, C, Same) :-
    tests_canon:t(N, Codes, Gold),
    ne(Gold, G),
    ( swi_ref:r(N, _, _, Ref) -> true ; Ref = missing ),
    catch(call_with_time_limit(10, ace_to_drs:acetext_to_drs(Codes, _, _, Drs, _)), _, Drs = err),
    ne(Ref, R), ne(Drs, C),
    ( Ref \== missing, variant(Ref, Drs) -> Same = 1 ; Same = 0 ).

ne(missing, x) :- !.
ne(err, 0) :- !.
ne(drs([], []), 0) :- !.
ne(_, 1).

%% Output-mode reference rows from the SWI run: om_ref(N, Type, ContentType, ContentAtom).
om_ref(N, T, CT, A) :- swi_om:r(N, T, CT, C), ( atom(C) -> A = C ; write_term_to_chars(C, [quoted(true)], Cs), atom_chars(A, Cs) ).

test_text(N, A) :- tests_canon:t(N, Cs, _), atom_codes(A, Cs).

%% Same call shape as harness/outmodes_swi.pl: raw get_ape_results/3, exceptions rendered quoted.
om_run(N, T, CT, C) :-
    test_text(N, A),
    catch(call_with_time_limit(10, ape:get_ape_results([text=A, solo=T], CT, C0)), E, (CT = err, C0 = '$exc'(E))),
    ( C0 = '$exc'(Ex) -> write_term_to_chars(Ex, [quoted(true)], Cs), atom_chars(C, Cs) ; C = C0 ).

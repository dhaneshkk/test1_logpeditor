/*  swi2scryer.pl — source-to-source converter: APE (SWI-Prolog dialect) -> Scryer-loadable ISO-ish Prolog.

    Usage:  swipl tools/swi2scryer.pl <ape_root> <out_root>

    Strategy: load APE in SWI first so every operator declaration (incl. ops exported between
    modules) is live; then re-read each source file term-by-term in its own module context and
    re-emit it with write_term/2 in standard syntax. Dialect-specific directives and goals are
    rewritten (see dir/3 and goal/2). Everything that cannot be translated is logged to
    MIGRATION_REPORT.txt in <out_root>.
*/
:- initialization(main, main).

:- dynamic report/2, cur_file/1, qualify/2.

%% Scryer (0.10) recurses forever on cyclic use_module/1,2 (SWI tolerates cycles).
%% cycle_break(ImportingFileSuffix, ImportedSpec, ImportedModule): drop the import edge and
%% module-qualify the calls instead; extra_load/2 makes sure the target is loaded elsewhere.
cycle_break('parser/sentence_failure.pl', 'grammar.plp', grammar).
cycle_break('utils/owlswrl/drs_to_owlswrl_core.pl', implication_to_swrl, implication_to_swrl).
extra_load('utils/owlswrl/drs_to_owlswrl.pl', use_module(implication_to_swrl)).

main :-
    current_prolog_flag(argv, [Root0, Out0|_]),
    absolute_file_name(Root0, Root), absolute_file_name(Out0, Out),
    working_directory(Old, Root),
    load_files('ape.pl', [silent(true)]),
    working_directory(_, Old),
    directory_file_path(Root, prolog, PRoot),
    findall(F, src_file(PRoot, F), Fs),
    forall(member(F, Fs), convert(PRoot, Out, F)),
    directory_file_path(Out, 'MIGRATION_REPORT.txt', Rep),
    setup_call_cleanup(open(Rep, write, S),
        forall(report(File, Msg), format(S, "~w: ~w~n", [File, Msg])), close(S)),
    aggregate_all(count, report(_,_), N), length(Fs, Len),
    forall(( directory_member('prolog-overrides', OvF, [recursive(true), extensions([pl])]),
             atom_concat('prolog-overrides/', Rel, OvF), directory_file_path(Out, Rel, Dst) ),
           ( copy_file(OvF, Dst), assert(report(Rel, override_installed)) )),
    format(user_error, "converted ~d files, ~d report lines -> ~w~n", [Len, N, Rep]).

src_file(Root, F) :-
    directory_member(Root, F, [recursive(true), extensions([pl, plp])]),
    \+ sub_atom(F, _, _, _, 'fit_to_plp'),
    \+ sub_atom(F, _, _, _, 'prologfeatures'),
    \+ sub_atom(F, _, _, _, 'clex_lexicon').      % inlined into clex.pl

out_path(PRoot, Out, F, OF) :-
    atom_concat(PRoot, '/', P1), atom_concat(P1, Rel0, F),
    file_name_extension(Base, _, Rel0), file_name_extension(Base, pl, Rel),
    directory_file_path(Out, Rel, OF).

convert(PRoot, Out, F) :-
    once(out_path(PRoot, Out, F, OF)),
    file_directory_name(OF, OD), make_directory_path(OD),
    retractall(cur_file(_)), assert(cur_file(F)),
    module_of_file(F, M),
    setup_call_cleanup(open(F, read, In, [encoding(utf8)]),
        read_all(In, M, Terms), close(In)),
    retractall(qualify(_,_)),
    needed_ops(M, Terms, Ops0),
    discontig(Terms, DPs), findall(discontiguous(PI), member(PI, DPs), DDs),
    ( DPs \== [] -> note(discontiguous_declared(DPs)) ; true ),
    append(Ops0, DDs, Ops),
    setup_call_cleanup(open(OF, write, OS, [encoding(utf8)]),
        ( format(OS, "%% AUTO-GENERATED by swi2scryer from ~w~n", [F]),
          forall(member(T-VN, Terms),
                 ( emit(OS, F, M, T, VN),
                   ( T = (:- module(_,_)) -> forall(member(O, Ops), wr_dir(OS, M, O, [])),
                       forall((extra_load(Suf, XL), atom_concat(_, Suf, F)), wr_dir(OS, M, XL, []))
                   ; true ) )),
          ( Terms = [(:- module(_,_))-_|_] -> true ; forall(member(O, Ops), true) ) ),
        close(OS)).

:- use_module(library(readutil)).
%% Operators visible in SWI module M, used (as atoms) in this file, unknown to Scryer by default.
needed_ops(M, Terms, Ops) :-
    findall(A, (member(T-_, Terms), term_atom(T, A)), As0), sort(As0, As),
    findall(op(P,Ty,N), ( member(N, As), \+ skip_op(N),
                          current_op(P, Ty, M:N), \+ scryer_op(P, Ty, N) ), Ops0),
    sort(Ops0, Ops).
term_atom(T, A) :- atom(T), !, A = T.
term_atom(T, A) :- compound(T), compound_name_arguments(T, F, Args),
    ( A = F ; member(X, Args), term_atom(X, A) ).
skip_op(N) :- memberchk(N, ['|', '$', '.', '{}', '[]', dynamic, discontiguous, multifile, initialization,
                            table, module_transparent, meta_predicate, thread_local, volatile, public, '?-']).
scryer_op(P, T, N) :- scryer_ops(L), memberchk(op(P,T,N), L).
scryer_ops(L) :- ( nb_current(scryer_ops, L) -> true
    ; read_file_to_terms('tools/scryer_ops.txt', L, []), nb_setval(scryer_ops, L) ).

module_of_file(F, M) :-
    ( module_property(M, file(F)) -> true
    ; file_name_extension(B, _, F), module_property(M, file(F2)), file_name_extension(B, _, F2) -> true
    ; M = user ).

read_all(In, M, Terms) :-
    read_term(In, T, [module(M), variable_names(VN), syntax_errors(error)]),
    (   T == end_of_file -> Terms = []
    ;   Terms = [T-VN|Rest], read_all(In, M, Rest)
    ).

note(Msg) :- cur_file(F), assert(report(F, Msg)).

%% ---------------------------------------------------------------- emission

emit(S, F, M, (:- D), VN) :- !,
    (   dir(D, F, Out) -> forall(member(O, Out), emit_out(S, M, O, VN))
    ;   note(dropped_directive(D))
    ).
emit(S, _F, M, (H --> B0), VN) :- !,          % DCG: rewrite plain goals inside {}/1
    dcg_body(B0, B), wr(S, M, (H --> B), VN).
emit(S, _F, M, (H :- B0), VN) :- !,
    goal(B0, B), wr(S, M, (H :- B), VN).
emit(S, _F, M, H, VN) :- wr(S, M, H, VN).

emit_out(S, M, raw(Text), _) :- !, format(S, "~w~n", [Text]), ignore(M = M).
emit_out(S, M, clauses(Cs), _) :- !, forall(member(C, Cs), wr(S, M, C, [])).
emit_out(S, M, D, VN) :- wr_dir(S, M, D, VN).

%% Directives are always written in functional notation: Scryer does not declare
%% dynamic/discontiguous/... as prefix operators.
wr_dir(S, M, D, VN) :-
    \+ \+ ( bind_names(VN), numbervars(D, 0, _, [singletons(true)]),
            compound_name_arguments(D, N, Args),
            format(S, ":- ~q(", [N]),
            wr_args(S, M, Args), format(S, ").~n", []) ).
wr_args(_, _, []).
wr_args(S, M, [A|As]) :-
    write_term(S, A, [quoted(true), module(M), numbervars(true), spacing(next_argument),
                      priority(999), portray(false), brace_terms(true)]),
    ( As == [] -> true ; write(S, ', '), wr_args(S, M, As) ).

wr(S, M, T, VN) :-
    \+ \+ ( bind_names(VN), numbervars(T, 0, _, [singletons(true)]),
            with_output_to(string(Str), write_term(T, [quoted(true), module(M), numbervars(true),
                              spacing(next_argument), ignore_ops(false),
                              fullstop(true), nl(true), portray(false),
                              no_lists(false), brace_terms(true)])),
            quote_dollar(Str, Str2), write(S, Str2) ).

%% SWI writes $-prefixed atoms unquoted; Scryer reads `$` as a symbol char -> quote them.
quote_dollar(S0, S) :-
    string_codes(S0, C0), qd(C0, 0'x, C), string_codes(S, C).
qd([], _, []).
qd([0'$|T], Prev, Out) :- \+ code_type(Prev, csym), Prev \== 0'', Prev \== 0'\\,
    T = [L|_], code_type(L, lower), !,
    span_csym(T, W, Rest), append([0''', 0'$|W], [0'''|R2], Out), last_or(W, Prev, P2), qd(Rest, P2, R2).
qd([C|T], _, [C|R]) :- qd(T, C, R).
span_csym([C|T], [C|W], R) :- code_type(C, csym), !, span_csym(T, W, R).
span_csym(R, [], R).
last_or(W, D, L) :- ( last(W, L) -> true ; L = D ).

bind_names([]).
bind_names([N=V|T]) :- ( var(V) -> V = '$VAR'(N) ; true ), bind_names(T).

%% ---------------------------------------------------------------- directives

dir(module(M, E0), _, [module(M, E), use_module(library(lists)), use_module(library(between)),
                       use_module(library(iso_ext)), use_module(library(charsio)),
                       use_module(library(dcgs)), use_module(library(error)),
                       use_module(library(terms)), use_module(library(time), [statistics/2]), use_module(library(random), []), use_module(SwiCompat)]) :- !,
    exclude([X]>>(X = op(_,_,_), \+ op_ok(X)), E0, E),
    compat_rel(SwiCompat).
dir(use_module(Spec), F, Out) :- !, dir(use_module(Spec, all), F, Out).
dir(use_module(Spec, I), F, Out) :-
    cycle_break(Suf, Spec, TM), atom_concat(_, Suf, F), !,
    note(cycle_broken(Spec)),
    ( is_list(I) -> forall(member(PI, I), assert(qualify(PI, TM))) ; true ),
    Out = [].
dir(use_module(Spec, I), F, Out) :- !,
    (   map_spec(Spec, F, S2) -> ( I == all -> Out = [use_module(S2)] ; Out = [use_module(S2, I)] )
    ;   note(dropped_import(Spec)), Out = []
    ).
dir(ensure_loaded(Spec), F, Out) :- !, dir(use_module(Spec, all), F, Out).
dir([H|T], F, Out) :- !, dir(use_module([H|T]), F, Out).
dir(dynamic(Ps), _, Out) :- !, pis(Ps, L), findall(dynamic(P), member(P, L), Out).
dir(discontiguous(Ps), _, Out) :- !, pis(Ps, L), findall(discontiguous(P), member(P, L), Out).
dir(multifile(Ps), _, Out) :- !, pis(Ps, L), findall(multifile(P), member(P, L), Out).
dir(op(P,T,N), _, [op(P,T,N)]) :- op_ok(op(P,T,N)), !.
dir(op(P,T,N), _, []) :- !, note(dropped_op(P,T,N)).
dir(style_check(_), _, []) :- !.
dir(encoding(_), _, []) :- !.
dir(set_prolog_flag(Fl, V), _, []) :- !, note(dropped_flag(Fl, V)).
dir(debug(_), _, []) :- !.
dir(initialization(G), _, [initialization(G2)]) :- !, goal(G, G2).
dir(initialization(G, _), _, [initialization(G2)]) :- !, goal(G, G2).
dir(assert(user:file_search_path(_,_)), _, []) :- !.
dir(format_predicate(C, G), _, [initialization(format_predicate(C, M:G))]) :- !,
    cur_file(F), module_of_file(F, M).
dir((prolog_load_context(directory, _), _), _, []) :- !.
%% clex.pl loads the big lexicon at load time -> inline it as clauses.
dir((clex_file(_), _), F, [clauses(Cs)]) :- !,
    file_directory_name(F, D), directory_file_path(D, 'clex_lexicon.pl', LF),
    setup_call_cleanup(open(LF, read, In, [encoding(utf8)]), read_all(In, clex, TVs), close(In)),
    findall(C, (member(C-_, TVs), C \= (:- _)), Cs).
dir(G, _, [initialization(G2)]) :- goal(G, G2), note(goal_directive_to_initialization(G)).

op_ok(op(_, _, N)) :- N \== ('!'), N \== ('|'), N \== ('{}').

pis(V, []) :- var(V), !.
pis((A,B), L) :- !, pis(A, LA), pis(B, LB), append(LA, LB, L).
pis([H|T], L) :- !, pis(H, LH), pis(T, LT), append(LH, LT, L).
pis([], []) :- !.
pis(_:P, L) :- !, pis(P, L).
pis(P, [P]).

compat_rel(Rel) :-
    cur_file(F), atom_concat(_, Tail, F), atom_concat('/prolog/', Sub, Tail), !,
    atomic_list_concat(Parts, '/', Sub), length(Parts, N), N1 is N - 1,
    length(Ups, N1), maplist(=('..'), Ups),
    append(Ups, [swi_compat], RP), atomic_list_concat(RP, '/', Rel).

map_spec(library(L), _, _) :- !, note(library_import(L)), fail.
map_spec(ape(P0), F, Rel) :- !,
    file_directory_name(F, D),
    sub_atom(F, Bf, _, _, '/prolog/'), !, sub_atom(F, 0, Bf, _, Base),
    atom_concat(Base, '/prolog/', PR), atom_concat(PR, P0, Abs0),
    rel_from(D, Abs0, Rel).
map_spec(P, _, Rel) :- atom(P), !,
    ( file_name_extension(B, plp, P) -> Rel = B ; file_name_extension(B, pl, P) -> Rel = B ; Rel = P ).

rel_from(FromDir, Abs, Rel) :-
    directory_file_path(FromDir, x, Dummy), relative_file_name(Abs, Dummy, Rel).

%% ---------------------------------------------------------------- goal rewriting

goal(V, V) :- var(V), !.
goal((A,B), (A2,B2)) :- !, goal(A, A2), goal(B, B2).
goal((A;B), (A2;B2)) :- !, goal(A, A2), goal(B, B2).
goal((A->B), (A2->B2)) :- !, goal(A, A2), goal(B, B2).
goal((A*->B), (A2*->B2)) :- !, goal(A, A2), goal(B, B2).
goal(\+ A, \+ A2) :- !, goal(A, A2).
goal(findall(T,G,L), findall(T,G2,L)) :- !, goal(G, G2).
goal(findall(T,G,L,R), findall(T,G2,L,R)) :- !, goal(G, G2).
goal(forall(A,B), forall(A2,B2)) :- !, goal(A, A2), goal(B, B2).
goal(once(A), once(A2)) :- !, goal(A, A2).
goal(ignore(A), ignore(A2)) :- !, goal(A, A2).
goal(catch(A,E,B), catch(A2,E,B2)) :- !, goal(A, A2), goal(B, B2).
goal(setup_call_cleanup(A,B,C), setup_call_cleanup(A2,B2,C2)) :- !, goal(A,A2), goal(B,B2), goal(C,C2).
goal(call_with_time_limit(T,G), call_with_time_limit(T,G2)) :- !, goal(G, G2).
goal(M:G, M:G2) :- !, goal(G, G2).
%% Rewrites match by *subsumption* (never bind variables of the source goal).
goal(G0, G) :- callable(G0), clause(rw(P, R), Body), subsumes_term(P, G0), P = G0, call(Body), !, G = R.
goal(G, TM:G) :- callable(G), functor(G, N, A), qualify(N/A, TM), !.
goal(G, G).

dcg_body(V, V) :- var(V), !.
dcg_body({G}, {G2}) :- !, goal(G, G2).
dcg_body((A,B), (A2,B2)) :- !, dcg_body(A, A2), dcg_body(B, B2).
dcg_body((A;B), (A2;B2)) :- !, dcg_body(A, A2), dcg_body(B, B2).
dcg_body((A|B), (A2|B2)) :- !, dcg_body(A, A2), dcg_body(B, B2).
dcg_body((A->B), (A2->B2)) :- !, dcg_body(A, A2), dcg_body(B, B2).
dcg_body(\+ A, \+ A2) :- !, dcg_body(A, A2).
dcg_body(call(G), call(G)) :- !.
dcg_body(X, X).

%% Scryer *replaces* a predicate whose clauses are discontiguous (SWI only warns), so
%% declare every such predicate discontiguous explicitly.
clause_pi((:- _), _) :- !, fail.
clause_pi((H --> _), N/A) :- !, strip_m(H, H1), functor(H1, N, A0), A is A0 + 2.
clause_pi((H :- _), PI) :- !, clause_pi(H, PI).
clause_pi(H, N/A) :- strip_m(H, H1), callable(H1), functor(H1, N, A).
strip_m(_:H, H) :- !.
strip_m(H, H).
discontig(Terms, DPs) :-
    findall(PI, (member(T-_, Terms), clause_pi(T, PI)), PIs),
    dc(PIs, none, [], [], DPs0), sort(DPs0, DPs).
dc([], _, _, D, D).
dc([P|Ps], Prev, Seen, D0, D) :-
    (   P == Prev -> dc(Ps, Prev, Seen, D0, D)
    ;   memberchk(P, Seen) -> dc(Ps, P, Seen, [P|D0], D)
    ;   dc(Ps, P, [P|Seen], D0, D)
    ).

%% ---------------------------------------------------------------- rewrite table
%% output capture
rw(with_output_to(atom(A), format(F,Args)), swi_format_atom(F, Args, A)) :- true.
rw(with_output_to(atom(A), format(F)), swi_format_atom(F, [], A)) :- true.
rw(with_output_to(atom(A), G), swi_with_output_to_atom(G2, A)) :- goal(G, G2).
rw(with_output_to(string(A), G), swi_with_output_to_atom(G2, A)) :- goal(G, G2), note(string_output_to_atom).
rw(format(atom(A), F, Args), swi_format_atom(F, Args, A)) :- true.
rw(format(string(A), F, Args), swi_format_atom(F, Args, A)) :- note(format_string_to_atom).
rw(sformat(A, F, Args), swi_format_atom(F, Args, A)) :- true.
rw(sformat(A, F), swi_format_atom(F, [], A)) :- true.
rw(must_be(T, X), swi_must_be(T, X)) :- true.
rw(X is random(N), swi_random(N, X)) :- true.
rw(atom_concat(A,B,C), swi_atom_concat(A,B,C)) :- true.
rw(atom_length(A,B), swi_atom_length(A,B)) :- true.
rw(atom_codes(A,B), swi_atom_codes(A,B)) :- true.
rw(atom_chars(A,B), swi_atom_chars(A,B)) :- true.
%% SWI module-qualified dynamic DB: assert(user:X) etc. kept; flagged
rw(assert(X), assertz(X)) :- true.

rw(format(F), swi_format(F, [])) :- true.
rw(format(F, A), swi_format(F, A)) :- true.
rw(format(S, F, A), swi_format(S, F, A)) :- true.
rw(T =.. L, swi_univ(T, L)) :- true.
rw(arg(N, T, A), swi_arg(N, T, A)) :- true.
rw(write_term(T, O), swi_write_term(T, O)) :- true.

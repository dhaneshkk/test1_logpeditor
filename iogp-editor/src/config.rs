//! Detector configuration: what the detection framework must run and evaluate for a rule set.

use crate::catalog::{Catalog, NounKind};
use crate::compile::{CondKind, Rule};
use serde_json::{json, Value};
use std::collections::BTreeSet;

pub const SCHEMA: &str = "iogp-alert-rules/v1";

/// One rule as a JSON object (stable schema for downstream consumers).
pub fn rule_json(r: &Rule) -> Value {
    json!({
        "id": r.id,
        "text": r.text,
        "paraphrase": r.paraphrase,
        "readback": r.readback,
        "lsr": {"id": r.alert.lsr, "name": r.alert.rule},
        "alert": {"type": r.alert.noun, "severity": r.alert.severity, "subject": r.alert.subject},
        "entities": r.entities,
        "conditions": r.conditions,
        "requires": requires(r),
        "fol": r.fol,
        "ape_tptp": r.ape_tptp,
        "warnings": r.warnings,
    })
}

fn requires(r: &Rule) -> Value {
    let (mut det, mut zones, mut sig) = (BTreeSet::new(), BTreeSet::new(), BTreeSet::new());
    for e in &r.entities {
        match &e.kind {
            NounKind::Class { detector, .. } => { det.insert(detector.clone()); }
            NounKind::Zone => { zones.insert(e.noun.clone()); }
            NounKind::Signal { source } => { sig.insert(format!("{} ({source})", e.noun)); }
            _ => {}
        }
    }
    for c in &r.conditions {
        match &c.kind { CondKind::Spatial { detector, .. } | CondKind::Association { detector, .. } => { det.insert(detector.clone()); } _ => {} }
    }
    json!({"detectors": det, "zones": zones, "signals": sig})
}

/// The whole rule set, as applied by the detection framework.
pub fn ruleset_json(cat: &Catalog, rules: &[Rule]) -> Value {
    let mut all = (BTreeSet::new(), BTreeSet::new(), BTreeSet::new());
    for r in rules {
        let q = requires(r);
        for d in q["detectors"].as_array().unwrap() { all.0.insert(d.as_str().unwrap().to_string()); }
        for d in q["zones"].as_array().unwrap() { all.1.insert(d.as_str().unwrap().to_string()); }
        for d in q["signals"].as_array().unwrap() { all.2.insert(d.as_str().unwrap().to_string()); }
    }
    json!({
        "schema": SCHEMA,
        "agent": cat.agent,
        "timing": {"grace_seconds": cat.defaults.grace_seconds, "cooldown_seconds": cat.defaults.cooldown_seconds},
        "semantics": {
            "time": "rules are evaluated at every frame time T",
            "within(S, T, D)": "T - D <= S <= T",
            "evidence": "a detected fact (object, zone membership, relation) stays believed for grace_seconds after it was last observed; a fact never observed, or not observed for longer than grace_seconds, is believed absent",
            "duration": "'for at least D seconds' means the believed condition held at every frame time in [T-D, T]; 'for more than D seconds' is the same with a strict bound",
            "negation": "'does not wear a harness' holds when no harness is believed associated with the subject; negated visual conditions require a duration (positive-evidence policy)",
            "counts": "'at least N workers' requires N distinct believed objects that satisfy every condition on them",
            "alert lifecycle": "per (rule, subject): IDLE -> ACTIVE when the rule's antecedent holds (alert raised once, with proof) -> COOLING when it stops holding -> IDLE after cooldown_seconds; re-raised only from IDLE",
            "fol": "each rule's 'fol' is a TPTP fof formula over believed facts at time T; the head is alert(Lsr, Severity, Subject, T)",
        },
        "requires": {"detectors": all.0, "zones": all.1, "signals": all.2},
        "rules": rules.iter().map(rule_json).collect::<Vec<_>>(),
    })
}

/// TPTP file of the whole rule set: domain axioms + one formula per rule.
pub fn ruleset_tptp(cat: &Catalog, rules: &[Rule]) -> String {
    let mut s = format!("% IOGP Life-Saving Rule alerts for {} — generated by iogp-editor (ACE via ape-rs)\n", cat.agent);
    s += "% Time-indexed FOL. within(S, T, D) <=> T - D =< S =< T (axiomatised by the runtime's clock).\n";
    s += "% Detector predicates: class(X) per detector label, zone-type(Z), relation(Subject, Object, Time).\n\n";
    for r in rules {
        s += &format!("% {}\n% {}\n{}\n\n", r.text, r.readback.join(" "), r.fol);
    }
    s
}
